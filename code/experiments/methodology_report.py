from __future__ import annotations

import argparse
from dataclasses import replace
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

CODE_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = CODE_ROOT.parent
SRC_ROOT = CODE_ROOT / "src"
for path in (SRC_ROOT, CODE_ROOT):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

from config.study_config import get_study_config
from visitas_analysis.reporting.methodology_report import write_methodology_table_snippets
from visitas_analysis.study.methodology_pipeline import run_methodology_pipeline

REPORT_DIR = REPO_ROOT / "reports" / "methodology_report"
DEFAULT_OUTPUT_DIR = CODE_ROOT / "outputs" / "methodology_report"
METHODOLOGY_SOURCE_FINGERPRINT = "03dd3d4ddd31cc2263be54900e1b25749fab8a7beb2033fbe796bf240fd4c39f"

# Later refined PPA results included in the report for comparison, but not
# generated by the methodology snapshot/pipeline itself.
EXTERNAL_REFINED_SNAPSHOT = (
    REPORT_DIR / "tables" / "90_refined_longitudinal_persistence_summary_snapshot.csv",
    REPORT_DIR / "tables" / "latex_longitudinal_refined_3241.tex",
    REPORT_DIR / "figures" / "refined_longitudinal_persistence_3241.png",
)


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def _stage_generated_assets(output_dir: Path, report_dir: Path) -> dict[str, list[str]]:
    """Stage generated aggregate assets without touching the external 3,241 snapshot."""
    generated_tables = output_dir / "tables"
    generated_figures = output_dir / "figures"
    report_tables = report_dir / "tables"
    report_figures = report_dir / "figures"
    report_tables.mkdir(parents=True, exist_ok=True)
    report_figures.mkdir(parents=True, exist_ok=True)

    staged_tables: list[str] = []
    staged_figures: list[str] = []
    for src in sorted(generated_tables.glob("*.csv")):
        dst = report_tables / src.name
        shutil.copy2(src, dst)
        staged_tables.append(str(dst.relative_to(REPO_ROOT)))
    for src in sorted(generated_figures.glob("*.png")):
        dst = report_figures / src.name
        shutil.copy2(src, dst)
        staged_figures.append(str(dst.relative_to(REPO_ROOT)))

    snippets = write_methodology_table_snippets(generated_tables, report_tables)
    staged_tables.extend(str(p.relative_to(REPO_ROOT)) for p in snippets)
    return {"tables": staged_tables, "figures": staged_figures}


def _compile_report(report_dir: Path) -> Path:
    """Compile methodology_report.tex; scientific calculations happen upstream."""
    tex = report_dir / "methodology_report.tex"
    latexmk = shutil.which("latexmk")
    if latexmk:
        subprocess.run([latexmk, "-pdf", "-interaction=nonstopmode", "-halt-on-error", tex.name], cwd=report_dir, check=True)
    else:
        pdflatex = shutil.which("pdflatex")
        biber = shutil.which("biber")
        if not pdflatex or not biber:
            raise RuntimeError("Compilation requires latexmk, or both pdflatex and biber.")
        subprocess.run([pdflatex, "-interaction=nonstopmode", "-halt-on-error", tex.name], cwd=report_dir, check=True)
        subprocess.run([biber, tex.stem], cwd=report_dir, check=True)
        subprocess.run([pdflatex, "-interaction=nonstopmode", "-halt-on-error", tex.name], cwd=report_dir, check=True)
        subprocess.run([pdflatex, "-interaction=nonstopmode", "-halt-on-error", tex.name], cwd=report_dir, check=True)
    pdf = report_dir / "methodology_report.pdf"
    if not pdf.exists():
        raise RuntimeError("LaTeX completed without creating methodology_report.pdf")
    return pdf


def _check_structure() -> list[str]:
    issues: list[str] = []
    required = [
        CODE_ROOT / "FUNCTION_INDEX.md",
        SRC_ROOT / "visitas_analysis" / "study" / "methodology_pipeline.py",
        SRC_ROOT / "visitas_analysis" / "study" / "extended_methodology.py",
        SRC_ROOT / "visitas_analysis" / "study" / "methodology_plots.py",
        REPORT_DIR / "methodology_report.tex",
        REPORT_DIR / "referencias.bib",
    ]
    for path in required:
        if not path.exists():
            issues.append(f"missing required path: {path}")
    for path in EXTERNAL_REFINED_SNAPSHOT:
        if not path.exists():
            issues.append(f"missing external refined snapshot: {path}")
    return issues


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Reproduce reports/methodology_report from controlled CMAT inputs.")
    parser.add_argument("--materias", type=Path, help="Override academic-record input path.")
    parser.add_argument("--asesorias", type=Path, help="Override CMAT advisory-record input path.")
    parser.add_argument("--extra-covariates", type=Path, help="Optional pre-treatment covariate file.")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--no-stage", action="store_true", help="Generate under code/outputs only.")
    parser.add_argument("--compile", action="store_true", help="Compile methodology_report.tex after staging.")
    parser.add_argument("--check", action="store_true", help="Validate structure without loading controlled data.")
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    issues = _check_structure()
    if issues:
        for issue in issues:
            print(f"[ERROR] {issue}", file=sys.stderr)
        return 2
    if args.check:
        print("[OK] methodology_report runner structure is complete.")
        print("[NOTE] Refined N=3,241 material remains an explicitly external later-stage snapshot.")
        return 0

    config = get_study_config(CODE_ROOT)
    config = replace(config, output_dir=args.output_dir.resolve())
    if args.materias:
        config = replace(config, materias_path=args.materias.resolve())
    if args.asesorias:
        config = replace(config, asesorias_path=args.asesorias.resolve())
    if args.extra_covariates:
        config = replace(config, extra_covariates_path=args.extra_covariates.resolve())

    for label, path in (("materias", Path(config.materias_path)), ("asesorias", Path(config.asesorias_path))):
        if not path.exists():
            print(f"[ERROR] controlled input {label} not found: {path}", file=sys.stderr)
            return 2

    result = run_methodology_pipeline(config)
    staged: dict[str, list[str]] = {"tables": [], "figures": []}
    if not args.no_stage:
        staged = _stage_generated_assets(Path(result["output_dir"]), REPORT_DIR)

    manifest = {
        "runner": str(Path(__file__).relative_to(REPO_ROOT)),
        "methodology_source_provenance_fingerprint": METHODOLOGY_SOURCE_FINGERPRINT,
        "inputs": {
            "materias": {"path": str(config.materias_path), "sha256": _sha256(Path(config.materias_path))},
            "asesorias": {"path": str(config.asesorias_path), "sha256": _sha256(Path(config.asesorias_path))},
            "extra_covariates": ({"path": str(config.extra_covariates_path), "sha256": _sha256(Path(config.extra_covariates_path))} if config.extra_covariates_path is not None and Path(config.extra_covariates_path).exists() else None),
        },
        "generated_output_dir": str(result["output_dir"]),
        "primary_mu_n": int(result["primary_n"]),
        "longitudinal_4211_risk_set_n": int(result["longitudinal_n"]),
        "staged": staged,
        "external_later_stage_snapshot_not_generated_here": [str(path.relative_to(REPO_ROOT)) for path in EXTERNAL_REFINED_SNAPSHOT],
        "report_prose_policy": "CSV tables, figures and LaTeX table snippets are regenerated. Review embedded numeric prose in methodology_report.tex whenever a new data extract changes results.",
    }
    manifest_path = Path(result["output_dir"]) / "methodology_report_build_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    if not args.no_stage:
        shutil.copy2(manifest_path, REPORT_DIR / "build_manifest.json")

    if args.compile:
        if args.no_stage:
            print("[ERROR] --compile cannot be combined with --no-stage.", file=sys.stderr)
            return 2
        print(f"[OK] compiled: {_compile_report(REPORT_DIR)}")

    print("[OK] methodology_report scientific pipeline completed.")
    print(f"Generated outputs: {result['output_dir']}")
    print(f"Primary MU cohort: {result['primary_n']}")
    print(f"Longitudinal 4,211-style risk set: {result['longitudinal_n']}")
    if not args.no_stage:
        print(f"Staged report assets: {REPORT_DIR}")
    print(f"Build manifest: {manifest_path}")
    print("[NOTE] Refined N=3,241 PPA material remains external by design.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
